class Command(BaseCommand):
    help = "Импортировать базовый набор ежедневных библейских цитат."

    def handle(self, *args, **options):
        created = 0
        updated = 0
        unchanged = 0
        duplicate_warnings = 0

        seen_references = set()
        seen_texts = set()

        with transaction.atomic():
            for order, item in enumerate(DAILY_QUOTES, start=1):
                text = item["text"].strip()
                source = item["source"].strip()
                reference = item["reference"].strip()

                if not text or not reference:
                    self.stdout.write(
                        self.style.WARNING(
                            f"Пропущена некорректная запись №{order}: нет текста или ссылки."
                        )
                    )
                    continue

                if reference in seen_references or text in seen_texts:
                    raise RuntimeError(
                        f"Дубль внутри импортируемого списка: {reference} — {text[:80]}"
                    )

                seen_references.add(reference)
                seen_texts.add(text)

                matches = DailyQuote.objects.filter(reference=reference).order_by("id")
                quote = matches.first()

                if quote is None:
                    DailyQuote.objects.create(
                        text=text,
                        source=source,
                        reference=reference,
                        quote_date=None,
                        is_active=True,
                        order=order,
                    )
                    created += 1
                    continue

                if matches.count() > 1:
                    duplicate_warnings += 1
                    self.stdout.write(
                        self.style.WARNING(
                            f"В БД уже несколько записей с {reference}; обновляю только первую (id={quote.id})."
                        )
                    )

                changed_fields = []
                desired = {
                    "text": text,
                    "source": source,
                    "quote_date": None,
                    "is_active": True,
                    "order": order,
                }

                for field, value in desired.items():
                    if getattr(quote, field) != value:
                        setattr(quote, field, value)
                        changed_fields.append(field)

                if changed_fields:
                    quote.save(update_fields=changed_fields)
                    updated += 1
                else:
                    unchanged += 1

        self.stdout.write(
            self.style.SUCCESS(
                f"Готово. Всего в наборе: {len(DAILY_QUOTES)}. "
                f"Создано: {created}. Обновлено: {updated}. "
                f"Без изменений: {unchanged}. "
                f"Предупреждений о дублях в БД: {duplicate_warnings}."
            )
        )
