const MAP = {uk:UK, csl_traditional:TRADITIONAL};
const mappedLesson = (base, locale) => {
  const value = locale?.[base.id];
  if (!value) return base;
  return {
    ...base,
    ...value,
    quotations:(value.quotations || []).map((quote,index) => ({
      ...base.quotations?.[index],
      ...quote,
    })),
    teachings:(value.teachings || []).map((teaching,index) => ({
      ...base.teachings?.[index],
      ...teaching,
    })),
  };
};

export const getLocalizedPrayerLessons = language =>
  PRAYER_LEARNING_LESSONS.map(lesson => mappedLesson(lesson, MAP[language]));
